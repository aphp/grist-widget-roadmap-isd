const STATUS_KEYS = new Set(['todo', 'inprogress', 'review', 'done']);

/**
 * Libellé français d'une clé, avec interpolation `{nom}`. Une clé inconnue est rendue telle quelle.
 * @param {string} key
 * @param {Record<string, string|number>} [vars]
 * @returns {string}
 */
export function label(key, vars) {
  const s = FR[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
}

/** Libellé court d'une part de la ventilation ETP : profil ISD (PO, DA, DS, DE), « Mgmt » ou « Autre ». */
export function etpLabel(key) {
  if (key === 'Autre') return FR['kanban.etpOther'];
  if (key === 'Mgmt') return FR['kanban.etpMgmt'];
  return label(`profile.${key}`);
}

/** Vrai si la clé existe dans le dictionnaire. */
export function hasLabel(key) {
  return key in FR;
}

/**
 * Libellé d'un statut de la Feuille : les quatre statuts connus sont traduits, les autres affichés tels quels.
 * @param {string} status
 */
export function statusLabel(status) {
  if (!status) return FR['status.none'];
  return STATUS_KEYS.has(status) ? FR[`status.${status}`] : status;
}

/** Nombre de tâches au singulier ou au pluriel. */
export function taskCount(n) {
  if (n === 0) return FR['count.none'];
  return n === 1 ? FR['count.task'] : label('count.tasks', { n: n.toLocaleString('fr-FR') });
}
